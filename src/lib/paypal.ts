/**
 * Retrieves the high-level connection and configuration statuses for the PayPal Gateway.
 * Strictly avoids exposing secrets or full credentials to the client.
 */
export function getPayPalGatewayStatus(): {
  oauthConfigured: boolean;
  webhookConfigured: boolean;
  webhookId: string | null;
  maskedClientId: string | null;
  environment: 'sandbox' | 'live';
} {
  const clientId = process.env.PAYPAL_SANDBOX_CLIENT_ID?.trim() || '';
  const clientSecret = process.env.PAYPAL_SANDBOX_CLIENT_SECRET?.trim() || '';
  const webhookId = process.env.PAYPAL_SANDBOX_WEBHOOK_ID?.trim() || '';

  const oauthConfigured = clientId.length > 5 && clientSecret.length > 5;
  const isWebhookConfigured = webhookId.length > 5 && !webhookId.includes('DEFAULT');

  let maskedClientId: string | null = null;
  if (clientId.length > 8) {
    maskedClientId = `${clientId.slice(0, 4)}••••••••${clientId.slice(-4)}`;
  } else if (clientId.length > 0) {
    maskedClientId = '••••••••••••••••••••••••';
  }

  return {
    oauthConfigured,
    webhookConfigured: isWebhookConfigured,
    webhookId: isWebhookConfigured ? webhookId : null,
    maskedClientId,
    environment: 'sandbox'
  };
}
