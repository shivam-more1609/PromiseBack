/**
 * Captures an approved PayPal Sandbox Checkout Order to produce a genuine capture ID.
 * Uses genuine APIMatic OrdersController: POST /v2/checkout/orders/{order_id}/capture
 */
export async function capturePayPalSandboxOrder(params: {
  orderId: string;
  idempotencyRequestId?: string;
}): Promise<{
  success: boolean;
  orderId?: string;
  captureId?: string;
  status?: string;
  amount?: number;
  currency?: string;
  createTime?: string;
  rawResponse?: Record<string, any>;
  error?: string;
}> {
  const { orderId, idempotencyRequestId } = params;

  if (!isPayPalSandboxConfigured()) {
    return {
      success: false,
      error: 'PAYPAL_SANDBOX_NOT_CONFIGURED: Cannot capture PayPal order without configured credentials.'
    };
  }

  try {
    const { ordersController } = getApimaticPayPalClient();
    const idempotency = idempotencyRequestId || `cap-idem-${Date.now()}-${Math.floor(1000 + Math.random() * 9000)}`;

    const resp = await ordersController.captureOrder({
      id: orderId,
      paypalRequestId: idempotency,
      prefer: 'return=representation',
      body: {}
    });

    const data = resp.result;
    const capture = data.purchaseUnits?.[0]?.payments?.captures?.[0];
    if (!capture || !capture.id) {
      return {
        success: false,
        orderId,
        error: 'PAYPAL_CAPTURE_MISSING: PayPal order captured successfully but no capture ID was returned.',
        rawResponse: data as any
      };
    }

    const captureStatus = capture.status || 'UNKNOWN';
    const amountVal = parseFloat(capture.amount?.value || '0');
    const currencyVal = capture.amount?.currencyCode || 'USD';

    return {
      success: captureStatus === 'COMPLETED',
      orderId: data.id,
      captureId: capture.id,
      status: captureStatus,
      amount: amountVal,
      currency: currencyVal,
      createTime: capture.createTime,
      rawResponse: data as any
    };
  } catch (err: any) {
    const message = err.message || JSON.stringify(err);
    const statusCode = err.statusCode || (err.response ? err.response.statusCode : 500);
    return {
      success: false,
      orderId,
      error: `PAYPAL_ORDER_CAPTURE_FAILED (HTTP ${statusCode}): ${message}`,
      rawResponse: err.result || err
    };
  }
}

